// Authentic 2D Pixel-Art Cat Sprite Engine
// Faithful reproduction of reference photo (taupe-mauve coat, cream muzzle & underbelly, pink blush, white tail tip)

export interface PixelRect {
  x: number;
  y: number;
  w: number;
  h: number;
  fill: string;
}

export interface SpriteFrame {
  width: number;
  height: number;
  rects: PixelRect[];
}

export const CAT_PALETTE: Record<string, string> = {
  '#': '#2B1810', // Dark warm chocolate brown outline
  '=': '#C7A99D', // Warm taupe coat (exact match to reference photo)
  '.': '#FDFFE3', // Cream / off-white muzzle, belly, socks, tail tip
  'P': '#DE7382', // Rosy pink blush & inner ears
  'W': '#FFFFFF', // Pure white highlight / sparkle
  'D': '#1C100B', // Deep dark pupil
  'R': '#E11D48', // Red-pink inner mouth & tongue
  'S': '#B09388', // Shading taupe
  'C': '#EBE5C8', // Cream shadow under paws
  'B': '#6366F1', // Indigo Zzz
  'L': '#818CF8', // Light indigo Zzz
  'Y': '#F59E0B', // Golden fish
  ' ': 'transparent',
};

function compileFrame(rows: string[]): SpriteFrame {
  const height = rows.length;
  const width = Math.max(...rows.map((r) => r.length));
  const rects: PixelRect[] = [];

  for (let y = 0; y < height; y++) {
    const row = rows[y];
    let startX = -1;
    let currentColor = '';

    for (let x = 0; x < width; x++) {
      const char = row[x] || ' ';
      const color = CAT_PALETTE[char] || 'transparent';

      if (color === 'transparent') {
        if (startX !== -1) {
          rects.push({ x: startX, y, w: x - startX, h: 1, fill: currentColor });
          startX = -1;
        }
      } else {
        if (startX === -1) {
          startX = x;
          currentColor = color;
        } else if (color !== currentColor) {
          rects.push({ x: startX, y, w: x - startX, h: 1, fill: currentColor });
          startX = x;
          currentColor = color;
        }
      }
    }
    if (startX !== -1) {
      rects.push({ x: startX, y, w: width - startX, h: 1, fill: currentColor });
    }
  }

  return { width, height, rects };
}

